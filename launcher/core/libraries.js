'use strict';
// Library resolution: maven coordinates to paths/URLs, rule filtering, legacy natives.
const path = require('path');
const { rulesAllow } = require('./rules');

/** "group:artifact:version[:classifier][@ext]" -> relative maven path. */
function mavenPath(coord) {
  let ext = 'jar';
  let c = coord;
  const at = c.indexOf('@');
  if (at !== -1) { ext = c.slice(at + 1); c = c.slice(0, at); }
  const [group, artifact, version, classifier] = c.split(':');
  if (!group || !artifact || !version) throw new Error(`Bad maven coordinate: ${coord}`);
  const file = `${artifact}-${version}${classifier ? `-${classifier}` : ''}.${ext}`;
  return [...group.split('.'), artifact, version, file].join('/');
}

function nativeClassifier(lib, platform) {
  if (!lib.natives) return null;
  const key = lib.natives[platform.name];
  if (!key) return null;
  return key.replace('${arch}', platform.arch === 'x86' ? '32' : '64');
}

/**
 * Returns {classpath: [{path,url,sha1,size,name}], natives: [...]} for the
 * merged version JSON. Paths are absolute under librariesDir.
 */
function resolveLibraries(version, librariesDir, platform, features = {}) {
  const classpath = [];
  const natives = [];
  for (const lib of version.libraries || []) {
    if (!rulesAllow(lib.rules, platform, features)) continue;
    const dl = lib.downloads || {};
    const native = nativeClassifier(lib, platform);
    if (native) {
      // Legacy (pre-1.19) natives: a classifier jar that gets extracted.
      const art = dl.classifiers && dl.classifiers[native];
      const rel = art ? art.path : mavenPath(`${lib.name}:${native}`);
      natives.push({
        name: lib.name,
        path: path.join(librariesDir, rel),
        url: art ? art.url : `${(lib.url || 'https://libraries.minecraft.net/').replace(/\/?$/, '/')}${rel}`,
        sha1: art && art.sha1,
        size: art && art.size,
        extract: lib.extract,
      });
      if (!dl.artifact) continue;
    }
    if (dl.artifact) {
      const rel = dl.artifact.path || mavenPath(lib.name);
      // Some forge libraries have an empty url: they are generated by the installer.
      classpath.push({
        name: lib.name,
        path: path.join(librariesDir, rel),
        url: dl.artifact.url || null,
        sha1: dl.artifact.sha1,
        size: dl.artifact.size,
      });
    } else if (!dl.classifiers) {
      const rel = mavenPath(lib.name);
      const base = (lib.url || 'https://libraries.minecraft.net/').replace(/\/?$/, '/');
      classpath.push({ name: lib.name, path: path.join(librariesDir, rel), url: `${base}${rel}`, sha1: lib.sha1, size: lib.size });
    }
  }
  return { classpath, natives };
}

module.exports = { mavenPath, resolveLibraries, nativeClassifier };
